export function generateGitignore(template?: string): string {
  const extra = template === 'rust' ? '\n**/*.rs.bk\n' : template === 'python' ? '\n__pycache__/\n*.pyc\n' : '';
  return `# General
node_modules/
dist/
build/
target/
.DS_Store
*.log
.env
.env.local
*.local${extra}
`;
}

export function generateReadme(draft: NewProjectDraft): string {
  const topicsList = draft.topics && draft.topics.length > 0 ? `\n**Tags:** ${draft.topics.map((t) => `\`${t}\``).join(' ')}\n` : '';
  const website = draft.website ? `\n🌐 [Website / Documentation](${draft.website})\n` : '';

  return `# ${draft.name}

${draft.description || 'A modern project managed with IRIS Operating Environment.'}
${topicsList}${website}
## Architecture & Overview
This repository uses structured, autonomous versioning with automated CI/CD binary builds.

## Getting Started
\`\`\`bash
# Clone the repository
git clone https://github.com/your-org/${draft.name}.git

# Navigate into directory
cd ${draft.name}
\`\`\`

## Releases & Automated Builds
Every tagged release (\`v*\`) triggers an automated GitHub Actions pipeline that packages and uploads production binaries.

---
*Created with IRIS Agentic Operating System v0.2.0*
`;
}

export function generateProjectScaffolding(draft: NewProjectDraft): { path: string; content: string }[] {
  const files: { path: string; content: string }[] = [];

  // README.md
  files.push({
    path: 'README.md',
    content: generateReadme(draft),
  });

  // .gitignore
  files.push({
    path: '.gitignore',
    content: generateGitignore(draft.template),
  });

  // LICENSE
  if (draft.license && draft.license !== 'None') {
    files.push({
      path: 'LICENSE',
      content: generateLicenseContent(draft.license),
    });
  }

  // GitHub Actions workflow
  if (draft.setupActionsWorkflow !== false) {
    files.push({
      path: '.github/workflows/release.yml',
      content: generateReleaseWorkflow(draft.name),
    });
  }

  return files;
}
