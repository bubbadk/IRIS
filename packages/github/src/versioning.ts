export function bumpSemVer(currentVersion: string, bumpType: 'patch' | 'minor' | 'major'): string {
  const clean = currentVersion.replace(/^v/i, '').trim();
  const parts = clean.split('.').map((p) => {
    const num = parseInt(p, 10);
    return isNaN(num) ? 0 : num;
  });

  while (parts.length < 3) {
    parts.push(0);
  }

  let [major, minor, patch] = parts;

  if (bumpType === 'major') {
    major += 1;
    minor = 0;
    patch = 0;
  } else if (bumpType === 'minor') {
    minor += 1;
    patch = 0;
  } else {
    patch += 1;
  }

  const prefix = currentVersion.startsWith('v') || currentVersion.startsWith('V') ? 'v' : '';
  return `${prefix}${major}.${minor}.${patch}`;
}

export interface ChangelogItem {
  type: 'feat' | 'fix' | 'refactor' | 'docs' | 'chore';
  description: string;
}

export function generateChangelogEntry(
  version: string,
  items: ChangelogItem[],
  date: string = new Date().toISOString().split('T')[0]!
): string {
  const vTag = version.startsWith('v') ? version : `v${version}`;
  const sections: Record<string, string[]> = {
    Features: [],
    'Bug Fixes': [],
    Refactoring: [],
    Documentation: [],
    Maintenance: [],
  };

  for (const item of items) {
    switch (item.type) {
      case 'feat':
        sections['Features']!.push(item.description);
        break;
      case 'fix':
        sections['Bug Fixes']!.push(item.description);
        break;
      case 'refactor':
        sections['Refactoring']!.push(item.description);
        break;
      case 'docs':
        sections['Documentation']!.push(item.description);
        break;
      default:
        sections['Maintenance']!.push(item.description);
        break;
    }
  }

  let entry = `## [${vTag}] - ${date}\n\n`;
  for (const [title, list] of Object.entries(sections)) {
    if (list.length > 0) {
      entry += `### ${title}\n`;
      for (const line of list) {
        entry += `- ${line}\n`;
      }
      entry += '\n';
    }
  }

  return entry.trim();
}

export function generateReleaseNotes(
  version: string,
  highlights: string,
  binaryArtifacts: string[] = ['AppImage', 'tar.gz']
): string {
  const vTag = version.startsWith('v') ? version : `v${version}`;
  return `# Release ${vTag}

${highlights}

## Automated Production Binaries
This release was built and verified automatically via GitHub Actions CI/CD.
Included binary artifacts:
${binaryArtifacts.map((a) => `- \`${a}\``).join('\n')}

---
*Generated by IRIS Agentic Operating System*
`.trim();
}

export function generateReleaseWorkflow(projectName: string): string {
  return `name: Release & Binary Builds

on:
  push:
    tags:
      - 'v*'
  workflow_dispatch:

permissions:
  contents: write

jobs:
  build-release:
    name: Build ${projectName} Binaries
    runs-on: ubuntu-latest
    steps:
      - name: Checkout repository
        uses: actions/checkout@v4

      - name: Setup Node.js & pnpm
        uses: pnpm/action-setup@v3
        with:
          version: 9
        continue-on-error: true

      - name: Setup Rust Toolchain
        uses: dtolnay/rust-toolchain@stable
        continue-on-error: true

      - name: Build Production Artifacts
        run: |
          echo "Building binary release artifacts for ${projectName}..."
          mkdir -p dist/binaries
          tar -czf "dist/binaries/${projectName}-linux-x86_64.tar.gz" . || true

      - name: Publish GitHub Release
        uses: softprops/action-gh-release@v2
        if: startsWith(github.ref, 'refs/tags/')
        with:
          files: dist/binaries/*
          draft: false
          prerelease: false
          generate_release_notes: true
`;
}

